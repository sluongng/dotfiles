#!/usr/bin/env python3

from __future__ import annotations

import argparse
from datetime import datetime
from pathlib import Path
import re
import shutil
import sys

try:
    import tomllib
except ModuleNotFoundError:  # Python 3.9/3.10 on stock macOS and older Linux.
    from _vendor import tomli as tomllib

GENERATED_HEADER_PREFIX = "# Generated by ~/.dotfiles/automation/codex/install-codex.sh."


PROJECTS_TABLE_RE = re.compile(r"^\[projects(?:\]|\.)")
PROJECTS_ENTRY_RE = re.compile(r"^\[projects\.")
PLUGIN_TABLE_RE = re.compile(r'^\[plugins\."([^"]+)"\]\s*$')


def read_text(path: Path) -> str:
    return path.read_text()


def display_path(path: Path) -> str:
    resolved = path.expanduser().resolve(strict=False)
    home = Path.home().resolve(strict=False)
    try:
        relative = resolved.relative_to(home)
    except ValueError:
        return str(resolved)

    if relative == Path("."):
        return "~"
    return f"~/{relative.as_posix()}"


def generated_header(local: Path, projects: Path) -> list[str]:
    return [
        GENERATED_HEADER_PREFIX,
        "# Edit shared settings in ~/.dotfiles/config/codex/config.toml.",
        f"# Optional machine-local additive settings belong in {display_path(local)}.",
        f"# Machine-local trust entries belong in {display_path(projects)}.",
    ]


def generated_footer(projects: Path) -> list[str]:
    return [
        "# New [projects.\"...\"] trust entries written here by Codex should be moved to",
        f"# {display_path(projects)}. Rerun ~/.dotfiles/automation/codex/install-codex.sh",
        "# to sync and clean them up.",
    ]


def reject_projects_table(path: Path, text: str) -> None:
    for line in text.splitlines():
        if PROJECTS_TABLE_RE.match(line.strip()):
            raise SystemExit(
                f"{path} must not define [projects]; use projects.local.toml instead"
            )


def parse_toml(path: Path, text: str) -> dict:
    try:
        return tomllib.loads(text)
    except tomllib.TOMLDecodeError as error:
        raise SystemExit(f"invalid TOML in {path}: {error}") from error
def remove_redundant_local_plugin_tables(
    shared_text: str, local_text: str, local_path: Path
) -> str:
    """Drop local plugin tables that are now identical to tracked desired state."""
    shared_plugins = parse_toml(Path("shared config"), shared_text).get("plugins", {})
    local_plugins = parse_toml(local_path, local_text).get("plugins", {})
    redundant: set[str] = set()

    for plugin_name, local_value in local_plugins.items():
        if plugin_name not in shared_plugins:
            continue
        if local_value != shared_plugins[plugin_name]:
            raise SystemExit(
                f'{local_path} overrides tracked plugin "{plugin_name}"; '
                "move the intended value to config/codex/config.toml or remove "
                "the local table"
            )
        redundant.add(plugin_name)

    if not redundant:
        return local_text

    output: list[str] = []
    skipping = False
    for raw_line in local_text.splitlines():
        stripped = raw_line.strip()
        if stripped.startswith("["):
            match = PLUGIN_TABLE_RE.match(stripped)
            skipping = bool(match and match.group(1) in redundant)
            if skipping:
                continue
        if not skipping:
            output.append(raw_line)

    names = ", ".join(sorted(redundant))
    print(f"Ignored redundant tracked plugin tables from {local_path}: {names}")
    return "\n".join(output).strip() + "\n"


def replace_table_value(text: str, table: str, key: str, value: str) -> str:
    output: list[str] = []
    current_table = ""
    replaced = False

    for raw_line in text.splitlines():
        stripped = raw_line.strip()
        if stripped.startswith("[") and stripped.endswith("]"):
            current_table = stripped
        if current_table == table and re.match(rf"^{re.escape(key)}\s*=", stripped):
            output.append(f"{key} = {value}")
            replaced = True
        else:
            output.append(raw_line)

    if not replaced:
        raise SystemExit(f"shared config is missing {table} {key}")
    return "\n".join(output) + "\n"


def upsert_table_value(text: str, table: str, key: str, value: str) -> str:
    output: list[str] = []
    current_table = ""
    found_table = False
    written = False

    for raw_line in text.splitlines():
        stripped = raw_line.strip()
        if stripped.startswith("[") and stripped.endswith("]"):
            if current_table == table and not written:
                output.append(f"{key} = {value}")
                written = True
            current_table = stripped
            found_table = found_table or current_table == table
        if current_table == table and re.match(rf"^{re.escape(key)}\s*=", stripped):
            output.append(f"{key} = {value}")
            written = True
        else:
            output.append(raw_line)

    if current_table == table and not written:
        output.append(f"{key} = {value}")
        written = True
    if not found_table or not written:
        raise SystemExit(f"shared config is missing {table}")
    return "\n".join(output) + "\n"


def remove_table(text: str, table: str) -> str:
    output: list[str] = []
    skipping = False
    found = False

    for raw_line in text.splitlines():
        stripped = raw_line.strip()
        if stripped.startswith("[") and stripped.endswith("]"):
            skipping = stripped == table
            found = found or skipping
            if skipping:
                continue
        if not skipping:
            output.append(raw_line)

    if not found:
        raise SystemExit(f"shared config is missing {table}")
    return "\n".join(output).rstrip() + "\n"


def extract_projects_tables(text: str, projects_path: Path) -> str:
    extracted: list[str] = []
    current_block: list[str] = []
    in_projects = False

    for raw_line in text.splitlines():
        line = raw_line.strip()
        if line.startswith("["):
            if PROJECTS_ENTRY_RE.match(line):
                if current_block:
                    extracted.extend(current_block)
                    if current_block[-1] != "":
                        extracted.append("")
                current_block = [raw_line]
                in_projects = True
                continue

            if in_projects:
                extracted.extend(current_block)
                if current_block and current_block[-1] != "":
                    extracted.append("")
                current_block = []
                in_projects = False

        if in_projects:
            if line.startswith("#"):
                continue
            current_block.append(raw_line)

    if current_block:
        extracted.extend(current_block)
        if current_block[-1] != "":
            extracted.append("")

    if not extracted:
        return ""

    header = [
        "# Local machine trust state for Codex projects.",
        f"# This file is updated by ~/.dotfiles/automation/codex/install-codex.sh for {display_path(projects_path.parent)}.",
        "# Do not move these entries into the tracked dotfiles config.",
        "",
    ]
    return "\n".join(header + extracted).rstrip() + "\n"


def sync_projects_from_target(target: Path, projects_path: Path) -> None:
    if not target.exists():
        return

    projects_text = extract_projects_tables(read_text(target), projects_path)
    if not projects_text:
        return

    projects_path.parent.mkdir(parents=True, exist_ok=True)
    projects_path.write_text(projects_text)
    print(f"Synced project trust entries to {projects_path}")


def build_rendered_config(
    shared: Path,
    local: Path,
    projects: Path,
    *,
    platform: str,
    nested_feature_tables: bool,
    marketplace_name: str,
    marketplace_source: Path,
) -> str:
    shared_text = read_text(shared)
    reject_projects_table(shared, shared_text)
    if not nested_feature_tables:
        shared_text = remove_table(shared_text, "[features.current_time_reminder]")
        shared_text = remove_table(shared_text, "[features.multi_agent_v2]")
        shared_text = remove_table(shared_text, "[agents]")
        shared_text = upsert_table_value(
            shared_text, "[features]", "multi_agent_v2", "true"
        )
        shared_text = upsert_table_value(
            shared_text, "[features]", "current_time_reminder", "true"
        )
    if platform == "Darwin":
        shared_text = replace_table_value(
            shared_text,
            '[plugins."chatgpt-threads@sluongng-dotfiles"]',
            "enabled",
            "false",
        )

    parts = [*generated_header(local, projects), "", shared_text.strip()]

    local_data: dict = {}
    if local.exists():
        local_text = read_text(local)
        reject_projects_table(local, local_text)
        local_text = remove_redundant_local_plugin_tables(
            shared_text, local_text, local
        )
        local_data = parse_toml(local, local_text)
        stripped = local_text.strip()
        if stripped:
            parts.extend(["", stripped])

    shared_data = parse_toml(shared, shared_text)
    known_marketplaces = {
        *shared_data.get("marketplaces", {}).keys(),
        *local_data.get("marketplaces", {}).keys(),
    }
    if marketplace_name not in known_marketplaces:
        source = str(marketplace_source.expanduser().resolve(strict=False))
        parts.extend(
            [
                "",
                f"[marketplaces.{marketplace_name}]",
                'source_type = "local"',
                f"source = {source!r}",
            ]
        )

    if projects.exists():
        projects_text = read_text(projects)
        stripped = projects_text.strip()
        if stripped:
            parts.extend(["", stripped])

    parts.extend(["", *generated_footer(projects)])
    rendered = "\n".join(parts).rstrip() + "\n"
    parse_toml(Path("rendered config"), rendered)
    return rendered


def backup_if_needed(target: Path) -> None:
    if target.is_symlink():
        target.unlink()
        print(f"Replaced symlinked {target} with a rendered config file")
        return

    if not target.exists():
        return

    current_text = target.read_text()
    if current_text.startswith(GENERATED_HEADER_PREFIX):
        return

    timestamp = datetime.now().strftime("%Y%m%d%H%M%S")
    backup = target.with_name(f"{target.name}.bak.{timestamp}")
    shutil.move(target, backup)
    print(f"Backed up {target} to {backup}")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--shared", required=True, type=Path)
    parser.add_argument("--local", required=True, type=Path)
    parser.add_argument("--projects", required=True, type=Path)
    parser.add_argument("--target", required=True, type=Path)
    parser.add_argument("--platform", required=True, choices=("Darwin", "Linux"))
    parser.add_argument(
        "--nested-feature-tables", required=True, choices=("true", "false")
    )
    parser.add_argument("--marketplace-name", required=True)
    parser.add_argument("--marketplace-source", required=True, type=Path)
    args = parser.parse_args()

    if not args.shared.exists():
        raise SystemExit(f"missing shared config: {args.shared}")

    sync_projects_from_target(args.target, args.projects)
    rendered = build_rendered_config(
        args.shared,
        args.local,
        args.projects,
        platform=args.platform,
        nested_feature_tables=args.nested_feature_tables == "true",
        marketplace_name=args.marketplace_name,
        marketplace_source=args.marketplace_source,
    )

    args.target.parent.mkdir(parents=True, exist_ok=True)
    backup_if_needed(args.target)
    args.target.write_text(rendered)
    print(f"Rendered {args.target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
